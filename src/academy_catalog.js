export function getPieceAcademyMeta(piece) {
  if (!piece) return null;
  const meta = PIECE_ACADEMY_META[piece.id];
  if (meta) {
    return {
      ...meta,
      composerObj: COMPOSER_BY_ID.get(meta.composerId) || COMPOSERS[0],
      genreObj: GENRE_BY_ID.get(meta.genreId) || MUSICAL_GENRES[0],
    };
  }
  return {
    composerId: "beethoven",
    genreId: "sonata",
    displayTitle: piece.title || "Произведение",
    era: "Классика",
    year: 1800,
    popularity: 70,
    difficultyLevel: 2,
    difficultyLabel: "Средний",
    keySignature: "—",
    story: "Концертное фортепианное произведение из репертуара студии.",
    learningTip: "Используйте замедление темпа и падающие ноты для детального разбора.",
    composerObj: COMPOSERS[0],
    genreObj: MUSICAL_GENRES[0],
  };
}
